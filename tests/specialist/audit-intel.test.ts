/**
 * Phase 7G — Audit Intelligence.
 *
 * This module reads the append-only ledger that every other control depends on, so the suite must
 * prove four things above all:
 *
 *   1. It NEVER writes to audit_log or enterprise_events. An audit reader that can modify the
 *      ledger it inspects destroys the property that makes the ledger worth having.
 *   2. It never declares an anomaly. POTENTIAL_ANOMALY paired with human review is the ceiling.
 *   3. An empty window is reported as empty WITH its bounds — silence is never assurance.
 *   4. Event classification is enforced against clearance, and an unrecognised clearance grants
 *      nothing (the Phase 7F escalation, re-tested on more sensitive data).
 *
 * NON-VACUITY. audit_log and enterprise_events are EMPTY at seed, so positive controls must first
 * generate real activity through the real platform and assert on it. Every positive control below
 * asserts a specific non-zero count.
 */
