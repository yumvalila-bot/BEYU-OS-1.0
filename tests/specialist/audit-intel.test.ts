describe("audit module — never mutates the ledger it inspects", () => {
  /**
   * The audit ledger GROWS as this module runs, because every ANALYSIS is itself audited. So a
   * naive count comparison is useless here. What must hold is that EXISTING rows are never
   * modified or removed — verified by xmin (catches even an idempotent UPDATE, the Phase 7F/7E
   * lesson) over a fixed set of pre-existing ids.
   */
  it("never modifies or deletes an existing audit record (xmin stable)", async () => {
    const before = await rowsOf<{ id: string; v: string }>(
      sql`select id, xmin::text as v from audit_log where object_id = ${generatedTraceIds[0]}`,
    );
    expect(before.length).toBeGreaterThan(0);

    await generateAuditReport(ctx(), { window: WINDOW });
    await analyzeFailedActions(ctx(), { window: WINDOW });
    await analyzePrivilegedActions(ctx(), ["specialist.treasury.analyze_cash"], { window: WINDOW });
    await inspectChain(ctx(), { window: WINDOW });

    const after = await rowsOf<{ id: string; v: string }>(
      sql`select id, xmin::text as v from audit_log where object_id = ${generatedTraceIds[0]}`,
    );
    expect(after).toEqual(before);
  });

  it("never modifies an existing enterprise event (xmin stable)", async () => {
    const before = await rowsOf<{ id: string; v: string }>(
      sql`select id, xmin::text as v from enterprise_events where subject_id = ${generatedTraceIds[0]}`,
    );
    expect(before.length).toBeGreaterThan(0);
    await correlateEvents(ctx(), { window: WINDOW });
    expect(await rowsOf<{ id: string; v: string }>(
      sql`select id, xmin::text as v from enterprise_events where subject_id = ${generatedTraceIds[0]}`,
    )).toEqual(before);
  });

  it("the immutability triggers remain armed", async () => {
    const rows = await rowsOf<{ tgname: string; tgenabled: string }>(sql`
      select t.tgname, t.tgenabled from pg_trigger t
      join pg_class c on c.oid = t.tgrelid
      where not t.tgisinternal and c.relname in ('audit_log','enterprise_events')
      order by t.tgname
    `);
    expect(rows).toHaveLength(4);
    expect(rows.every((r) => r.tgenabled === "O")).toBe(true);
  });

  it("defines no tables of its own", async () => {
    const names = (await rowsOf<{ table_name: string }>(sql`
      select table_name from information_schema.tables
      where table_schema = 'public' and (table_name like '%audit%' or table_name like '%event%')
      order by table_name
    `)).map((r) => r.table_name);
    // The ledger-domain tables: baseline + internal_event_receipts (Phase 8
    // governed cross-OS event idempotency — part of the ledger domain, RLS-
    // isolated like audit_log). Nothing else added.
    expect(names).toEqual([
      "audit_chain_heads",
      "audit_log",
      "employment_events",
      "enterprise_events",
      "internal_event_receipts",
    ]);
  });

  it("adds no migration", async () => {
    // 25 = migrations 0000-0019 (prior baseline) + 0020_service_principals
    // + 0021_financial_ledger_rls + 0022_chart_of_accounts_tenant_uniqueness
    // + 0023_noelia_ai_platform
    // + 0024_noelia_model_runtime
    // (Phase 8 events, Phase 6 service-principal registry, ledger RLS,
    // chart-of-accounts tenant hardening and Phase 1 Noelia AI platform:
    // all additive/hardening).
    expect(await count(sql`select count(*)::int as n from public.beyu_migrations`)).toBe(25);
  });

  it("leaves the decision registry entirely PENDING", async () => {
    expect(await count(sql`select count(*)::int as n from governance_decision_registry where status <> 'PENDING'`)).toBe(0);
  });
});

afterAll(async () => {
  // The ledgers legitimately grew (this module audits itself). What must remain true is that the
  // immutability controls are still armed and no decision was activated.
  const disabled = await count(sql`select count(*)::int as n from pg_trigger where tgenabled = 'D' and not tgisinternal`);
  expect(disabled).toBe(0);
});
