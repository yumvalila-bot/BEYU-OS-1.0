describe("audit service — positive controls on real ledger activity", () => {
  it("searches and finds the real records this suite generated", async () => {
    const r = await searchAuditRecords(ctx(), { window: WINDOW });
    expect(r.version).toBe(AUDIT_INTEL_VERSION);
    expect(r.data.records.length).toBeGreaterThanOrEqual(3);
    const found = r.data.records.filter((x) => generatedTraceIds.includes(x.objectId));
    expect(found).toHaveLength(3);
    expect(found.every((x) => x.action === "specialist.treasury.analyze_cash")).toBe(true);
    expect(found.every((x) => x.outcome === "SUCCESS")).toBe(true);
  });

  it("filters by actor, action and outcome against real data", async () => {
    const byActor = await searchAuditRecords(ctx(), { window: WINDOW, actorUserId: "USR_GENERATOR" });
    expect(byActor.data.records.length).toBeGreaterThanOrEqual(3);
    expect(byActor.data.records.every((x) => x.actorUserId === "USR_GENERATOR")).toBe(true);

    const byOutcome = await searchAuditRecords(ctx(), {
      window: WINDOW,
      outcome: "DENIED",
      actorUserId: "USR_GENERATOR",
    });
    // This suite generated no denials for USR_GENERATOR. Other suites (HTTP 403,
    // TOTP replay) may append DENIED rows to the same tenant ledger; a global
    // empty-DENIED assertion is therefore not an invariant of this module.
    expect(byOutcome.data.records).toHaveLength(0);
    expect(byOutcome.explanation.join(" ")).toMatch(/not evidence that the activity never occurred/i);
  });

  it("Phase 7G FIX: real records carry a trace id and the authorising permission", async () => {
    const r = await searchAuditRecords(ctx(), { window: WINDOW, actorUserId: "USR_GENERATOR" });
    const record = r.data.records.find((x) => x.objectId === generatedTraceIds[0])!;
    // Before this phase both were absent: trace_id was NULL and permission was never recorded.
    expect(record.traceId).toBe(generatedTraceIds[0]);

    const [row] = await rowsOf<{ perm: string }>(
      sql`select new_value->>'permission' as perm from audit_log where object_id = ${generatedTraceIds[0]}`,
    );
    expect(row.perm).toBe("finance:treasury.read");
  });

  it("correlates real audit records with their real events", async () => {
    const r = await correlateEvents(ctx(), { window: WINDOW });
    const mine = r.data.correlations.filter((c) => generatedTraceIds.includes(c.traceId));
    expect(mine).toHaveLength(3);
    expect(mine.every((c) => c.complete)).toBe(true);
    expect(mine.every((c) => c.auditRecordIds.length === 1 && c.eventIds.length === 1)).toBe(true);
  });

  it("analyses real actor activity", async () => {
    const r = await analyzeActorActivity(ctx(), { window: WINDOW });
    const generator = r.data.actors.find((a) => a.actorUserId === "USR_GENERATOR")!;
    expect(generator).toBeDefined();
    expect(generator.totalActions).toBeGreaterThanOrEqual(3);
    expect(generator.successCount).toBeGreaterThanOrEqual(3);
    expect(generator.distinctActions).toContain("specialist.treasury.analyze_cash");
  });

  it("returns a real timeline ordered by sequence", async () => {
    const r = await readActivityTimeline(ctx(), { window: WINDOW });
    expect(r.data.entries.length).toBeGreaterThanOrEqual(3);
    const seqs = r.data.entries.map((e) => e.sequence);
    const sorted = [...seqs].sort(compareSequence);
    expect(seqs).toEqual(sorted);
  });

  it("inspects the real chain and reports linkage honestly", async () => {
    const r = await inspectChain(ctx(), { window: WINDOW });
    expect(r.data.recordsInspected).toBeGreaterThanOrEqual(3);
    expect(r.data.verificationScope).toMatch(/does NOT recompute/i);
    expect(r.explanation.join(" ")).toMatch(/gaps are expected/i);
  });

  it("generates a real report with observations and explicit refusals", async () => {
    const r = await generateAuditReport(ctx(), { window: WINDOW });
    expect(r.data.auditRecordCount).toBeGreaterThanOrEqual(3);
    expect(r.data.eventCount).toBeGreaterThanOrEqual(3);
    expect(r.data.actorCount).toBeGreaterThanOrEqual(1);
    expect(r.data.outcomeCounts.SUCCESS).toBeGreaterThanOrEqual(3);
    expect(r.data.topActions.length).toBeGreaterThan(0);
    expect(r.data.unsupported).toHaveLength(3);
    expect(r.explanation.join(" ")).toMatch(/freezes nothing, revokes nothing and remediates nothing/i);
  });

  it("reports an empty window as empty, with its bounds", async () => {
    const r = await generateAuditReport(ctx(), { window: { from: "2019-01-01", to: "2019-01-02" } });
    expect(r.data.auditRecordCount).toBe(0);
    expect(r.data.basis).toBe("DATA_NOT_AVAILABLE");
    const empty = r.data.observations.find((o) => o.code === "EMPTY_WINDOW")!;
    expect(empty.detail).toContain("2019-01-01");
    expect(empty.detail).toMatch(/not assurance that nothing happened/i);
  });

  it("analyses governance activity over real records", async () => {
    const r = await analyzeGovernanceActivity(ctx(), { window: WINDOW });
    // The generated records are SPECIALIST_RESULT, not governance objects: correctly zero.
    expect(r.data.basis).toBe("OBSERVED");
    expect(r.data.records.every((x) => x.objectType !== "SPECIALIST_RESULT")).toBe(true);
    expect(r.data.explanation.join(" ")).toMatch(/not inference from action names/i);
  });

  it("reports unsupported analyses through the service", async () => {
    const r = await reportUnsupportedAnalyses(ctx());
    expect(r.data.unsupported.map((u) => u.analysis).sort()).toEqual([
      "AUTHENTICATION_EVENTS", "BEHAVIOURAL_BASELINE", "RETENTION_COMPLIANCE",
    ]);
  });

  it("is deterministic across repeated runs", async () => {
    const a = await analyzeActorActivity(ctx(), { window: WINDOW });
    const b = await analyzeActorActivity(ctx(), { window: WINDOW });
    // Actor totals grow as this suite audits itself, so compare the stable shape rather than counts.
    expect(a.data.actors.map((x) => x.actorUserId).sort()).toEqual(b.data.actors.map((x) => x.actorUserId).sort());
  });
});

