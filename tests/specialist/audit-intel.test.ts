describe("audit service — hostile inputs", () => {
  it("rejects malformed trace ids", async () => {
    for (const traceId of ["", "short", "has space", "x".repeat(65)]) {
      await expect(searchAuditRecords(ctx({ traceId }))).rejects.toMatchObject({ code: "RULE_VIOLATION" });
    }
  });

  it("rejects a malformed or inverted window rather than defaulting", async () => {
    await expect(searchAuditRecords(ctx(), { window: { from: "01/01/2026", to: "2026-12-31" } }))
      .rejects.toThrow(/ISO date/i);
    await expect(searchAuditRecords(ctx(), { window: { from: "2026-12-31", to: "2026-01-01" } }))
      .rejects.toThrow(/must not be after/i);
  });

  it("rejects a nonsensical limit", async () => {
    await expect(searchAuditRecords(ctx(), { window: WINDOW, limit: 0 })).rejects.toThrow(/positive integer/i);
    await expect(searchAuditRecords(ctx(), { window: WINDOW, limit: -5 })).rejects.toThrow(/positive integer/i);
  });

  it("does not expose sensitive audit payload fields", async () => {
    const r = await searchAuditRecords(ctx(), { window: WINDOW });
    const record = r.data.records[0] as unknown as Record<string, unknown>;
    // ip_address, user_agent, old_value and new_value are deliberately not surfaced.
    expect(record).not.toHaveProperty("ipAddress");
    expect(record).not.toHaveProperty("userAgent");
    expect(record).not.toHaveProperty("oldValue");
    expect(record).not.toHaveProperty("newValue");
  });

  it("does not activate or alter any capability", async () => {
    const before = await rowsOf(sql`select capability_code, activation_status from governance_capability_registry order by capability_code`);
    await generateAuditReport(ctx(), { window: WINDOW });
    expect(await rowsOf(sql`select capability_code, activation_status from governance_capability_registry order by capability_code`)).toEqual(before);
  });

  it("registers audit capabilities with every enforcement path LOCKED", async () => {
    const rows = await rowsOf<{ capability_code: string; activation_status: string; required_decisions: string[] }>(
      sql`select capability_code, activation_status, required_decisions from governance_capability_registry
          where capability_code like 'CAP_SPEC_AUDIT%' order by capability_code`,
    );
    expect(rows.every((r) => r.activation_status === "LOCKED")).toBe(true);
    for (const code of ["CAP_SPEC_AUDIT_REMEDIATE", "CAP_SPEC_AUDIT_FREEZE", "CAP_SPEC_AUDIT_ENFORCE"]) {
      const cap = rows.find((r) => r.capability_code === code)!;
      expect(cap).toBeDefined();
      expect(cap.required_decisions.length).toBeGreaterThan(0);
    }
    expect(rows.find((r) => r.capability_code === "CAP_SPEC_AUDIT_ENFORCE")!.required_decisions).toContain("P1");
  });

  it("creates no enforcement permission", async () => {
    expect(await count(sql`
      select count(*)::int as n from role_permissions
      where permission_code in ('audit:enforce','audit:freeze','audit:remediate','finance:ledger.approve')
    `)).toBe(0);
  });

  it("creates no journal entries and funds no capital", async () => {
    await generateAuditReport(ctx(), { window: WINDOW });
    expect(await count(sql`select count(*)::int as n from journal_entries`)).toBe(0);
    expect(await count(sql`select count(*)::int as n from capital_requests where status = 'FUNDED'`)).toBe(0);
  });
});

