describe("audit engines — absence is never assurance", () => {
  it("returns DATA_NOT_AVAILABLE, not 'no activity', for an empty record set", () => {
    const r = actorActivity([]);
    expect(r.basis).toBe("DATA_NOT_AVAILABLE");
    expect(r.actors).toEqual([]);
    expect(r.explanation.join(" ")).toMatch(/not evidence that no activity occurred/i);
  });

  it("returns DATA_NOT_AVAILABLE for an empty timeline and empty failure analysis", () => {
    expect(activityTimeline([]).basis).toBe("DATA_NOT_AVAILABLE");
    expect(failedActionAnalysis([]).basis).toBe("DATA_NOT_AVAILABLE");
    expect(governanceActivity([]).basis).toBe("DATA_NOT_AVAILABLE");
  });

  it("never reports a single-record chain as verified", () => {
    const r = inspectEvidenceChain([{ sequence: "1", hash: "h", prevHash: null }]);
    expect(r.linkageVerified).toBeNull();
    expect(r.basis).toBe("DATA_NOT_AVAILABLE");
    expect(r.explanation.join(" ")).toMatch(/would overstate the check/i);
  });

  it("never reports an empty chain as verified", () => {
    const r = inspectEvidenceChain([]);
    expect(r.linkageVerified).toBeNull();
    expect(r.recordsInspected).toBe(0);
  });

  it("states the limits of what chain verification proves", () => {
    const r = inspectEvidenceChain([
      { sequence: "1", hash: "a", prevHash: null },
      { sequence: "2", hash: "b", prevHash: "a" },
    ]);
    expect(r.linkageVerified).toBe(true);
    expect(r.verificationScope).toMatch(/does NOT recompute cryptographic digests/i);
    expect(r.verificationScope).toMatch(/does NOT prove the chain was never rewritten/i);
  });
});

