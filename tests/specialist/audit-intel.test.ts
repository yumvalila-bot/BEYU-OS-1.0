describe("audit service — permission and clearance", () => {
  it("denies a principal without audit:log.read", async () => {
    // HCM_DIRECTOR has no audit permission at all.
    const hcm = principal({ roles: ["HCM_DIRECTOR"] });
    expect(hcm.permissions.has("audit:log.read" as never)).toBe(false);
    await expect(searchAuditRecords(ctx({ principal: hcm }))).rejects.toMatchObject({ code: "DENIED" });
  });

  it("denies a principal with no roles", async () => {
    await expect(searchAuditRecords(ctx({ principal: principal({ roles: [] }) })))
      .rejects.toMatchObject({ code: "DENIED" });
  });

  it("POSITIVE: AUDITOR holds audit:log.read and succeeds", async () => {
    const r = await searchAuditRecords(ctx({ principal: principal({ roles: ["AUDITOR"] }) }), { window: WINDOW });
    expect(r.data.records.length).toBeGreaterThanOrEqual(3);
  });

  it("CRITICAL: correlation requires audit:event.read, not just audit:log.read", async () => {
    // CHIEF_RISK_COMPLIANCE holds audit:log.read but NOT audit:event.read.
    const crc = principal({ roles: ["CHIEF_RISK_COMPLIANCE"] });
    expect(crc.permissions.has("audit:log.read" as never)).toBe(true);
    expect(crc.permissions.has("audit:event.read" as never)).toBe(false);
    await expect(correlateEvents(ctx({ principal: crc }), { window: WINDOW }))
      .rejects.toThrow(/audit:event.read/i);
  });

  it("the full report also requires audit:event.read", async () => {
    const crc = principal({ roles: ["CHIEF_RISK_COMPLIANCE"] });
    await expect(generateAuditReport(ctx({ principal: crc }), { window: WINDOW }))
      .rejects.toThrow(/audit:event.read/i);
  });

  it("CRITICAL: an unrecognised clearance grants NO event visibility (fails closed)", async () => {
    const forged = principal({ roles: ["AUDITOR"], clearance: "SUPER_ADMIN" as never });
    const r = await correlateEvents(ctx({ principal: forged }), { window: WINDOW });
    // Every event is withheld; no correlation can be completed from event data.
    expect(r.data.withheldEventCount).toBeGreaterThan(0);
    expect(r.data.correlations.every((c) => c.eventIds.length === 0)).toBe(true);
  });

  it("POSITIVE: a recognised clearance sees events and reports zero withheld", async () => {
    const r = await correlateEvents(ctx({ principal: principal({ roles: ["AUDITOR"] }) }), { window: WINDOW });
    expect(r.data.withheldEventCount).toBe(0);
    expect(r.data.correlations.some((c) => c.eventIds.length > 0)).toBe(true);
  });

  it("states that a clearance-limited result is PARTIAL", async () => {
    const forged = principal({ roles: ["AUDITOR"], clearance: "NONSENSE" as never });
    const r = await correlateEvents(ctx({ principal: forged }), { window: WINDOW });
    expect(r.explanation.join(" ")).toMatch(/PARTIAL/);
  });
});

