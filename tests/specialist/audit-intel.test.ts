describe("audit engines — no anomaly is ever declared", () => {
  it("reports denials as OBSERVED facts, not accusations", () => {
    const r = failedActionAnalysis([rec({ id: "A", outcome: "DENIED" })]);
    expect(r.observations[0].code).toBe("DENIED_ACTION");
    expect(r.observations[0].basis).toBe("OBSERVED");
    expect(r.explanation.join(" ")).toMatch(/not by itself evidence of an attack/i);
  });

  it("flags repetition ONLY against a caller-supplied threshold", () => {
    const denials = [1, 2, 3].map((i) => rec({ id: `A${i}`, outcome: "DENIED" }));
    const noThreshold = failedActionAnalysis(denials);
    expect(noThreshold.observations.filter((o) => o.code === "REPEATED_DENIAL")).toHaveLength(0);
    expect(noThreshold.explanation.join(" ")).toMatch(/no ratified threshold to default to/i);

    const withThreshold = failedActionAnalysis(denials, { repeatedDenialThreshold: 3 });
    const flagged = withThreshold.observations.find((o) => o.code === "REPEATED_DENIAL")!;
    expect(flagged.basis).toBe("POTENTIAL_ANOMALY");
    expect(flagged.detail).toMatch(/not a finding of misconduct/i);
  });

  it("rejects a nonsensical repetition threshold", () => {
    expect(() => failedActionAnalysis([rec()], { repeatedDenialThreshold: 0 })).toThrow(/positive integer/i);
    expect(() => failedActionAnalysis([rec()], { repeatedDenialThreshold: 1.5 })).toThrow(/positive integer/i);
  });

  it("never emits a verdict stronger than POTENTIAL_ANOMALY", () => {
    const all = [
      ...failedActionAnalysis([rec({ outcome: "DENIED" })], { repeatedDenialThreshold: 1 }).observations,
      ...auditDataQuality([rec({ occurredAt: "2030-01-01T00:00:00.000Z" })], [], { asOf: "2026-02-15" }).observations,
    ];
    expect(all.length).toBeGreaterThan(0);
    for (const o of all) {
      expect(["OBSERVED", "POTENTIAL_ANOMALY", "REQUIRES_HUMAN_REVIEW"]).toContain(o.basis);
      expect(o.advisoryOnly).toBe(true);
    }
  });

  it("does not infer privilege from action names", () => {
    const dangerous = [
      rec({ id: "A", action: "finance.ledger.delete" }),
      rec({ id: "B", action: "admin.superuser.grant" }),
    ];
    const r = privilegedActionAnalysis(dangerous, []);
    expect(r.basis).toBe("DATA_NOT_AVAILABLE");
    expect(r.records).toEqual([]);
    expect(r.explanation.join(" ")).toMatch(/will not infer it from action names/i);
  });

  it("counts privileged actions only from the caller's declared list", () => {
    const r = privilegedActionAnalysis(
      [rec({ id: "A", action: "governance.decision.approve" }), rec({ id: "B", action: "read.something" })],
      ["governance.decision.approve"],
    );
    expect(r.records.map((x) => x.id)).toEqual(["A"]);
    expect(r.explanation.join(" ")).toMatch(/expected activity, not a finding/i);
  });

  it("performs no statistical baseline analysis", () => {
    const unsupported = unsupportedAnalyses();
    const baseline = unsupported.find((u) => u.analysis === "BEHAVIOURAL_BASELINE")!;
    expect(baseline.basis).toBe("DATA_NOT_AVAILABLE");
    expect(baseline.explanation.join(" ")).toMatch(/manufacture accusations/i);
  });

  it("refuses authentication analysis because no auth history exists", () => {
    const auth = unsupportedAnalyses().find((u) => u.analysis === "AUTHENTICATION_EVENTS")!;
    expect(auth.basis).toBe("DATA_NOT_AVAILABLE");
    expect(auth.explanation.join(" ")).toMatch(/would measure live sessions, not authentication behaviour/i);
  });

  it("refuses retention analysis because no retention policy is represented", () => {
    const ret = unsupportedAnalyses().find((u) => u.analysis === "RETENTION_COMPLIANCE")!;
    expect(ret.missingInputs.join(" ")).toMatch(/no retention period/i);
  });
});

