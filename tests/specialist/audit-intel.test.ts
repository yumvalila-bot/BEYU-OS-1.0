describe("audit engines — correlation and evidence chain", () => {
  it("correlates an audit record with its event by trace id", () => {
    const r = correlate([rec()], [evt()]);
    expect(r.correlations).toHaveLength(1);
    expect(r.correlations[0].complete).toBe(true);
    expect(r.correlations[0].auditRecordIds).toEqual(["AUD_SYN"]);
    expect(r.correlations[0].eventIds).toEqual(["EVT_SYN"]);
  });

  it("reports an orphaned event without inventing an audit record", () => {
    const r = correlate([], [evt()]);
    expect(r.correlations[0].complete).toBe(false);
    expect(r.correlations[0].auditRecordIds).toEqual([]);
    expect(r.observations.map((o) => o.code)).toContain("ORPHANED_EVENT");
    expect(r.explanation.join(" ")).toMatch(/No counterpart record is ever synthesised/i);
  });

  it("reports an orphaned audit record without inventing an event", () => {
    const r = correlate([rec()], []);
    expect(r.correlations[0].complete).toBe(false);
    expect(r.observations.map((o) => o.code)).toContain("ORPHANED_AUDIT_RECORD");
  });

  it("flags a record with no trace id as uncorrelatable", () => {
    const r = correlate([rec({ traceId: null })], []);
    expect(r.observations.map((o) => o.code)).toContain("MISSING_TRACE_ID");
  });

  it("detects a hash-chain discontinuity", () => {
    const r = inspectEvidenceChain([
      { sequence: "1", hash: "a", prevHash: null },
      { sequence: "2", hash: "b", prevHash: "WRONG" },
    ]);
    expect(r.linkageVerified).toBe(false);
    expect(r.discontinuities).toHaveLength(1);
    expect(r.discontinuities[0].atSequence).toBe("2");
    expect(r.discontinuities[0].detail).toMatch(/may indicate a gap in the queried scope rather than tampering/i);
  });

  it("orders by sequence exactly, beyond Number precision", () => {
    // Sequences past 2^53 must still order correctly.
    expect(compareSequence("9007199254740993", "9007199254740992")).toBeGreaterThan(0);
    expect(compareSequence("100", "99")).toBeGreaterThan(0);
    expect(compareSequence("5", "5")).toBe(0);
    const r = activityTimeline([rec({ id: "B", sequence: "1000" }), rec({ id: "A", sequence: "999" })]);
    expect(r.entries.map((e) => e.sequence)).toEqual(["999", "1000"]);
    expect(r.explanation.join(" ")).toMatch(/clock adjustment cannot reorder history/i);
  });
});

